// Scan v4 for morally/religiously loaded language and for culture-bound example
// sentences (scripture-style quotes). Writes a human-readable report to
// v5/derived/audit-language.md and prints a summary. This surfaces candidates
// for the neutrality change-set; it does not modify anything.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadDomTree, flatten } from './lib.mjs';

const DERIVED = fileURLToPath(new URL('../derived/', import.meta.url));
mkdirSync(DERIVED, { recursive: true });

// Terms that signal an embedded value judgment. Word-boundary matched, case-insensitive.
const LOADED = [
  'immoral', 'immorality', 'pervert', 'perverted', 'perversion', 'sinful', 'sin',
  'wicked', 'evil', 'depraved', 'degenerate', 'ungodly', 'godless', 'godlessness',
  'unholy', 'unnatural', 'illicit', 'lewd', 'obscene', 'vile', 'sodomy', 'heathen',
  'pagan', 'infidel', 'blasphem', 'abomination',
];
// Slurs / pejoratives that should not be lead example words.
const SLURS = ['pervert', 'perverted', 'homo', 'faggot', 'queer', 'fag', 'dyke', 'retard'];
// Heuristic for scripture-style example sentences.
const SCRIPTURE = /\b(God|LORD|Jesus|Christ|Holy Spirit|heaven and earth|the Lord|thy|thou|thee)\b/;

const loadedRe = new RegExp('\\b(' + LOADED.join('|') + ')', 'i');
const slurRe = new RegExp('\\b(' + SLURS.join('|') + ')\\b', 'i');

const { roots } = loadDomTree();
const all = flatten(roots);

const loadedHits = [];
const slurHits = [];
const scriptureHits = [];

for (const d of all) {
  const nameDesc = `${d.name} — ${d.description}`;
  if (loadedRe.test(nameDesc)) loadedHits.push({ code: d.code, name: d.name, where: 'name/desc', text: nameDesc });
  d.questions.forEach((q, i) => {
    if (loadedRe.test(q.question)) loadedHits.push({ code: d.code, name: d.name, where: `Q${i + 1}`, text: q.question });
    if (q.exampleWords && slurRe.test(q.exampleWords))
      slurHits.push({ code: d.code, name: d.name, where: `Q${i + 1} words`, text: q.exampleWords });
    if (q.exampleSentences && SCRIPTURE.test(q.exampleSentences))
      scriptureHits.push({ code: d.code, name: d.name, where: `Q${i + 1} sentence`, text: q.exampleSentences });
  });
}

function section(title, hits) {
  const lines = [`## ${title} (${hits.length})`, ''];
  for (const h of hits) lines.push(`- **${h.code} ${h.name}** [${h.where}]: ${h.text.replace(/\n/g, ' ')}`);
  lines.push('');
  return lines.join('\n');
}

const md = [
  '# Language audit (v4)', '',
  'Auto-generated by `v5/scripts/audit-language.mjs`. Candidates for the',
  'neutrality change-set — review before acting; not all hits need changes.', '',
  section('Morally/religiously loaded name/description/question text', loadedHits),
  section('Slur or pejorative example words', slurHits),
  section('Scripture-style example sentences', scriptureHits),
].join('\n');

writeFileSync(DERIVED + 'audit-language.md', md);
console.log(`Language audit: ${loadedHits.length} loaded, ${slurHits.length} slur, ${scriptureHits.length} scripture-style -> derived/audit-language.md`);
