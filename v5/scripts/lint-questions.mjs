// Style linter for elicitation questions, per v5/STYLE-GUIDE.md. Flags questions
// that are long, non-template, rhetorical/yes-no, or idiomatic. Writes
// v5/derived/lint-questions.md and a count summary. Advisory only.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadDomTree, flatten } from './lib.mjs';

const DERIVED = fileURLToPath(new URL('../derived/', import.meta.url));
mkdirSync(DERIVED, { recursive: true });

const MAX_WORDS = 25;
// Approved opening frames (after stripping a leading "(N)" number).
const TEMPLATE = /^(what|which|how)\b/i;
const WORDY_TEMPLATE = /^what words\b/i;
// Yes/no or rhetorical openers.
const YESNO = /^(is|are|do|does|did|can|could|should|would|will|has|have|was|were)\b/i;
const IDIOMS = [
  'beat around the bush', 'kick the bucket', 'under the weather', 'piece of cake',
  'break a leg', 'hit the sack', 'let the cat out', 'spill the beans', 'a dime a dozen',
];

const { roots } = loadDomTree();
const all = flatten(roots);

const findings = [];
let total = 0;
for (const d of all) {
  d.questions.forEach((q, i) => {
    total++;
    const body = q.question.replace(/^\(\d+\)\s*/, '').trim();
    const wordCount = body.split(/\s+/).length;
    const flags = [];
    if (wordCount > MAX_WORDS) flags.push(`long(${wordCount}w)`);
    if (YESNO.test(body)) flags.push('yes/no or rhetorical');
    else if (!TEMPLATE.test(body)) flags.push('non-template opener');
    else if (!WORDY_TEMPLATE.test(body)) flags.push('non-standard frame');
    const low = body.toLowerCase();
    if (IDIOMS.some((idm) => low.includes(idm))) flags.push('idiom');
    if (flags.length) findings.push({ code: d.code, name: d.name, q: i + 1, flags, text: body });
  });
}

// Group counts by primary flag for the summary (strip any "(...)" detail).
const byFlag = {};
for (const f of findings) {
  for (const fl of f.flags) {
    const key = fl.split('(')[0];
    byFlag[key] = (byFlag[key] || 0) + 1;
  }
}

const md = ['# Question style lint (v4)', '',
  `Auto-generated by \`v5/scripts/lint-questions.mjs\`. ${findings.length} of ${total} questions flagged.`,
  'Advisory — feeds exemplar rewrites in `changes/questions.yaml`; full rewrite is follow-on work.', '',
  '## Counts by flag', '',
  ...Object.entries(byFlag).sort((a, b) => b[1] - a[1]).map(([k, v]) => `- ${k}: ${v}`),
  '', '## Flagged questions (first 300)', ''];
for (const f of findings.slice(0, 300)) md.push(`- **${f.code}** Q${f.q} [${f.flags.join(', ')}]: ${f.text}`);
md.push('');

writeFileSync(DERIVED + 'lint-questions.md', md.join('\n'));
console.log(`Question lint: ${findings.length}/${total} flagged -> derived/lint-questions.md`);
console.log('  by flag: ' + Object.entries(byFlag).map(([k, v]) => `${k}=${v}`).join(', '));
